ZB.LOCALES = { pt:"pt-PT", en:"en-US", it:"it-IT" };
ZB.FLAGS = { pt:"🇵🇹", en:"🇬🇧", it:"🇮🇹" };
ZB.LANGNAME = { pt:"Português", en:"English", it:"Italiano" };

(function () {
  let lang = "pt";
  try { const s = localStorage.getItem("zb_site_lang"); if (s && ZB.I18N[s]) lang = s; } catch (e) {}
  ZB.lang = lang;

  ZB.t = (k) => (ZB.I18N[ZB.lang] && ZB.I18N[ZB.lang][k]) || ZB.I18N.pt[k] || k;

  ZB.applyI18n = function () {
    document.documentElement.lang = ZB.lang;
    document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = ZB.t(el.dataset.i18n); });
    document.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = ZB.t(el.dataset.i18nHtml); });
    document.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = ZB.t(el.dataset.i18nPh); });
    const code = document.getElementById("langCode");
    const flag = document.getElementById("langFlag");
    if (code) code.textContent = ZB.lang.toUpperCase();
    if (flag) flag.textContent = ZB.FLAGS[ZB.lang];
    document.querySelectorAll("#langMenu button").forEach(b => b.classList.toggle("active", b.dataset.lang === ZB.lang));
  };

  ZB.setLang = function (l) {
    if (!ZB.I18N[l]) return;
    ZB.lang = l;
    try { localStorage.setItem("zb_site_lang", l); } catch (e) {}
    ZB.applyI18n();
    window.dispatchEvent(new CustomEvent("zb:langchange", { detail: l }));
  };

  document.addEventListener("DOMContentLoaded", function () {
    ZB.applyI18n();
    const langBtn = document.getElementById("langBtn");
    const langMenu = document.getElementById("langMenu");
    if (langBtn && langMenu) {
      langBtn.addEventListener("click", (e) => { e.stopPropagation(); langMenu.classList.toggle("open"); });
      langMenu.querySelectorAll("button").forEach(b =>
        b.addEventListener("click", () => { ZB.setLang(b.dataset.lang); langMenu.classList.remove("open"); }));
      document.addEventListener("click", () => langMenu.classList.remove("open"));
    }
  });
})();
