/* ===================== COUNT-UP ===================== */
function countUp(el){
  const target=+el.dataset.count, pre=el.dataset.prefix||"", suf=el.dataset.suffix||"";
  let cur=0; const dur=1200, t0=performance.now();
  function step(now){
    const p=Math.min((now-t0)/dur,1); const ease=1-Math.pow(1-p,3);
    cur=Math.round(target*ease);
    el.textContent=pre+cur.toLocaleString(LOC[lang])+suf;
    if(p<1)requestAnimationFrame(step);
  }
  requestAnimationFrame(step);
}

/* ===================== REVEAL ===================== */
let revObs;
function observeReveal(){
  if(!revObs){
    revObs=new IntersectionObserver(es=>{
      es.forEach(e=>{ if(e.isIntersecting){
        e.target.classList.add("in");
        e.target.querySelectorAll?.("[data-count]").forEach(countUp);
        if(e.target.dataset&&e.target.dataset.count)countUp(e.target);
        revObs.unobserve(e.target);
      }});
    },{threshold:.18});
  }
  $$(".reveal:not(.in)").forEach(el=>revObs.observe(el));
  $$("[data-count]").forEach(el=>{ if(!el.closest(".reveal")) revObs.observe(el); });
}

