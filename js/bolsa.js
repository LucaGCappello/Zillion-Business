function priceBand(ask){ // normalize roughly to EUR millions for filter (BRL/AED treated nominally)
  const m=ask/1000000; if(m<3)return"0-3"; if(m<7)return"3-7"; if(m<15)return"7-15"; return"15-999";
}

function renderGrid(){
  const q=$("#fSearch").value.trim().toLowerCase();
  const sec=$("#fSector").value, ctr=$("#fCountry").value, pr=$("#fPrice").value, sort=$("#fSort").value;
  let list=LISTINGS.filter(L=>{
    if(sec && L.sector!==sec)return false;
    if(ctr && L.country!==ctr)return false;
    if(pr && priceBand(L.ask)!==pr)return false;
    if(q){const hay=(L.code+" "+t("sector_"+L.sector)+" "+t("country_"+L.country)+" "+L.teaser[lang]).toLowerCase(); if(!hay.includes(q))return false;}
    return true;
  });
  if(sort==="pd")list.sort((a,b)=>b.ask-a.ask);
  else if(sort==="pa")list.sort((a,b)=>a.ask-b.ask);
  else if(sort==="rv")list.sort((a,b)=>b.revenue-a.revenue);
  else if(sort==="nw")list.sort((a,b)=>b.year-a.year);
  else list.sort((a,b)=>(b.featured?1:0)-(a.featured?1:0));

  const grid=$("#grid");
  grid.innerHTML=list.length?list.map(listingCard).join(""):`<div class="empty">${t("empty")}</div>`;
  $("#resCount").textContent=list.length;
  grid.querySelectorAll(".card").forEach(c=>{
    c.style.opacity=0;c.style.transform="translateY(14px)";
    requestAnimationFrame(()=>{c.style.transition="opacity .45s var(--ease),transform .45s var(--ease)";c.style.opacity=1;c.style.transform="none";});
    c.addEventListener("click",()=>openModal(c.dataset.code));
  });
}

